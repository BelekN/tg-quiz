/**
 * Резерв места под нижним таббаром внутри потока контента.
 *
 * НЕ через pb-* на <Screen>: у него уже есть класс safe-bottom
 * (обычное CSS-правило в index.css, объявленное ПОСЛЕ
 * `@import "tailwindcss"`), которое задаёт тот же padding-bottom —
 * при равной специфичности в каскаде выигрывает то, что compiled-CSS
 * ставит позже, а это всегда safe-bottom, независимо от того, какой
 * pb-* написан в JSX. Поэтому — отдельный элемент в потоке, а не спор
 * за то же самое CSS-свойство на том же узле.
 *
 * h-24 — под собственную высоту таббара (иконка+подпись+паддинги),
 * safe-bottom — под отступ под "домашней" полосой снизу, как и у
 * самого таббара.
 */
export default function TabBarSpacer() {
  return <div className="safe-bottom h-24" aria-hidden="true" />
}
