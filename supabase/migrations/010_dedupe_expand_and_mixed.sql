-- ------------------------------------------------------------
-- 3) Снова убираем перекос позиции правильного ответа — теперь
-- по ВСЕЙ таблице (500 строк), тем же приёмом, что в 008.
-- ------------------------------------------------------------
with target as (
  select id, options, correct_option_index,
         (row_number() over (order by id))::int % 4 as new_correct
    from public.questions
),
rebuilt as (
  select
    t.id,
    t.new_correct,
    t.options[t.correct_option_index + 1] as correct_text,
    (
      select array_agg(opt order by ord)
        from unnest(t.options) with ordinality as u(opt, ord)
       where ord - 1 <> t.correct_option_index
    ) as distractors
    from target t
)
update public.questions q
   set options = (
         r.distractors[1:r.new_correct] || array[r.correct_text] || r.distractors[r.new_correct + 1:3]
       ),
       correct_option_index = r.new_correct
  from rebuilt r
 where q.id = r.id;

-- ------------------------------------------------------------
-- 4) "Случайный микс" в Квиз-тестах: start_solo с p_category =
-- 'mixed' теперь берёт вопросы из ВСЕХ категорий, а не одной.
-- ------------------------------------------------------------
create or replace function public.start_solo(
  p_tg_id    bigint,
  p_category text,
  p_count    integer default 10
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ids       uuid[];
  v_session   public.solo_sessions;
  v_questions jsonb;
begin
  select array_agg(q.id) into v_ids
    from (
      select id from public.questions
       where is_active
         and (p_category = 'mixed' or category = p_category)
       order by random()
       limit p_count
    ) q;

  if coalesce(array_length(v_ids, 1), 0) = 0 then
    raise exception 'NO_QUESTIONS_IN_CATEGORY';
  end if;

  insert into public.solo_sessions (tg_id, category, question_ids)
  values (p_tg_id, p_category, v_ids)
  returning * into v_session;

  select jsonb_agg(
           jsonb_build_object(
             'id',       q.id,
             'question', q.question,
             'options',  q.options,
             'category', q.category
           ) order by t.ord
         )
    into v_questions
    from unnest(v_session.question_ids) with ordinality as t(qid, ord)
    join public.questions q on q.id = t.qid;

  return jsonb_build_object(
    'session_id', v_session.id,
    'category',   v_session.category,
    'questions',  v_questions
  );
end $$;
