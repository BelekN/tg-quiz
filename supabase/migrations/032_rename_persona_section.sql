-- ------------------------------------------------------------
-- Раздел "Кто ты из..." переименован в "Узнай себя" — с 20 тестами
-- (стресс, привязанность, шопинг, язык любви и т.д.) старое название
-- буквально "кто ты из [персонажей/жанров]" уже не описывает половину
-- контента. Обновляем категорию и тексты у трёх завязанных на него
-- достижений; сами persona_tests/persona_results старое название не
-- упоминали, их трогать не нужно.
-- ------------------------------------------------------------
update public.achievements
   set category = 'Узнай себя'
 where category = 'Кто ты из...';

update public.achievements
   set description = 'Пройди свой первый тест в разделе «Узнай себя»'
 where key = 'first_persona';

update public.achievements
   set description = 'Пройди все тесты в разделе «Узнай себя»'
 where key = 'all_personas';
